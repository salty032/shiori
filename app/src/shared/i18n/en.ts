// missing or misspelled key a compile error, so `npm run typecheck` is the guard against
// half-translated builds.
//
// Writing rules — follow these instead of translating the Japanese literally:
//   * Sentence case for every label and button ("Export selected", never "Export Selected").
//   * Buttons are verb phrases; labels, toggles and headings are noun phrases.
//   * Errors state what happened, then what the user should do about it.
//   * Address the user as "you"; call the app "Shiori", never "the application".
//   * Prefer plain words over jargon: "folder" not "directory", "delete" not "remove".
